class CatalogCodeError extends Error {
  constructor(message, statusCode = 400, code = 'INVALID_CATALOG_CODE') {
    super(message); this.name = 'CatalogCodeError'; this.statusCode = statusCode; this.code = code;
  }
}

const CP_PATTERN = /^CP\d{6,}$/;

async function allocateCatalogCode(client) {
  const result = await client.query(
    `SELECT format_catalog_code(nextval('catalog_code_seq'::regclass)) AS code`,
  );
  return result.rows[0].code;
}

function rejectClientCatalogCode(value) {
  if (value !== undefined) throw new CatalogCodeError('product_code is generated by the server and cannot be supplied');
}

function isCatalogCode(value) { return CP_PATTERN.test(String(value || '').trim().toUpperCase()); }

module.exports = { CatalogCodeError, CP_PATTERN, allocateCatalogCode, rejectClientCatalogCode, isCatalogCode };
