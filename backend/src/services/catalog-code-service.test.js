const test = require('node:test');
const assert = require('node:assert/strict');
const { allocateCatalogCode, rejectClientCatalogCode, isCatalogCode } = require('./catalog-code-service');

test('catalog code recognition uses only the permanent CP namespace', () => {
  assert.equal(isCatalogCode('cp000001'), true);
  assert.equal(isCatalogCode('CP1000000'), true);
  assert.equal(isCatalogCode('CP123'), false);
  assert.equal(isCatalogCode('CT000001'), false);
});

test('catalog codes come from the PostgreSQL sequence formatter', async () => {
  const calls = [];
  const client = { query: async (sql) => { calls.push(sql); return { rows: [{ code: 'CP000042' }] }; } };
  assert.equal(await allocateCatalogCode(client), 'CP000042');
  assert.match(calls[0], /nextval\('catalog_code_seq'/);
});

test('clients cannot assign catalog codes', () => {
  assert.doesNotThrow(() => rejectClientCatalogCode(undefined));
  assert.throws(() => rejectClientCatalogCode('CP000001'), /generated by the server/);
});
